#!/usr/bin/env python3
"""Generate ignored EDF build configuration from maintained project inputs."""
import argparse
import os
from pathlib import Path
import sys
from edf_platforms import PLATFORMS, select_platform

ROOT = Path(__file__).resolve().parents[1]
MARKER = "# Generated by scripts/configure-edf.py; edit software/edf configuration instead.\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=ROOT / "software/edf/workspace")
    parser.add_argument("--platform", choices=PLATFORMS)
    parser.add_argument("--shared-workspace", type=Path,
                        help="Reuse an existing workspace's sources, downloads, and sstate cache")
    args = parser.parse_args()
    if sys.platform != "linux" or os.environ.get("PETALINUX"):
        parser.error("Use a fresh native Linux shell without PetaLinux")
    workspace = args.workspace.resolve()
    platform, settings = select_platform(workspace, args.platform)
    if args.shared_workspace:
        shared = args.shared_workspace.resolve(strict=True)
        links = [(workspace / name, shared / name) for name in ["sources", "downloads", "sstate-cache"]]
        for path, target in links:
            if not target.is_dir():
                parser.error(f"Shared workspace directory is missing: {target}")
            if (path.exists() or path.is_symlink()) and path.resolve() != target.resolve():
                parser.error(f"Refusing to replace {path}")
        workspace.mkdir(parents=True, exist_ok=True)
        for path, target in links:
            if not path.is_symlink() and not path.exists():
                path.symlink_to(target, target_is_directory=True)
    sources = workspace / "sources"
    template = sources / "meta-amd-edf/conf/templates/default/bblayers.conf.sample"
    if not template.is_file():
        parser.error("Fetch EDF sources first with scripts/setup-edf.py")
    conf = workspace / "build/conf"
    conf.mkdir(parents=True, exist_ok=True)
    files = {
        "bblayers.conf": template.read_text().replace("##OEROOT##", str(sources / "poky")) +
            '\nBBLAYERS += "' + ' '.join(str(p) for p in [
                sources / "meta-sdr", ROOT / "software/petalinux/meta-platform-common",
                ROOT / "software/edf/meta-sonar"]) + '"\n',
        "local.conf": (ROOT / "software/edf/conf/local.conf").read_text().replace(
            "@EDF_WORKSPACE@", str(workspace)).replace("@EDF_HARDWARE_CONF@", settings["hardware_conf"]),
    }
    # Never replace a developer's independently maintained configuration.
    for name in files:
        path = conf / name
        if path.exists() and not path.read_text().startswith(MARKER):
            parser.error(f"Refusing to overwrite unmanaged configuration: {path}")
    for name, content in files.items():
        path = conf / name
        payload = MARKER + content
        if not path.exists() or path.read_text() != payload:
            path.write_text(payload)
    marker = workspace / ".edf-platform"
    if not marker.exists():
        marker.write_text(platform + "\n")
    hardware = conf / settings["hardware_conf"]
    if not hardware.exists():
        hardware.write_text('# Bootstrap machine for native tooling only; import hardware before building an image.\n'
                            f'MACHINE = "{settings["soc"]}-generic"\n')
    print(f"Configured {workspace / 'build'}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        sys.exit(str(error))
